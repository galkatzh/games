#!/usr/bin/env node
// tools/ayalon.mjs — WP-RENDER
// `node tools/ayalon.mjs`. Writes content/tlv_center/ayalon.js from the raw extract: the motorway and motorway_link ways that pass 4 of
// the importer drops (ARCHITECTURE 6.6). Scenery only. The file feeds js/render/ground.js and nothing else, so the drivable graph, the
// map and its hash cannot move: this tool writes nothing under data/maps and does not touch the importer.
//
// Identical input gives byte-identical output. A tunnel is left out, because the ground pass cannot show what is under it.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { boxOf, clipLine, loadSources, makeProjection, projectNodes, simplifyLine } from './lib/osm.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const AREA = 'tlv_center';
/** The fence is simplified to the same 0.3 m, so the drawn edge and the sim's wall stay together. Decimetres. */
const SIMPLIFY_DM = 3;
/** A way with no lanes tag. */
const DEFAULT_LANES = { motorway: 3, motorway_link: 1 };

/**
 * @param {object} way OSM way.
 * @returns {boolean} True for a way on the motorway network.
 */
function isMotorway(way) {
  return !!way.tags && (way.tags.highway === 'motorway' || way.tags.highway === 'motorway_link');
}

/**
 * The lines to draw, lowest first, so a flyover paints over what it crosses, and a ramp under the carriageway it leaves.
 * @param {object} osm From `loadSources`.
 * @param {object} box Decimetre box.
 * @param {object} proj Projection.
 * @returns {Array<{osm: number, link: number, lanes: number, mouth: number[], pts: number[]}>}
 */
export function motorwayLines(osm, box, proj) {
  const ways = [...osm.ways.values()].filter(isMotorway).sort((a, b) => a.id - b.id);
  const uses = new Map();
  for (const w of ways) for (const id of new Set(w.nodes)) uses.set(id, (uses.get(id) || 0) + 1);
  const rows = [];
  for (const w of ways) {
    if (w.tags.tunnel && w.tags.tunnel !== 'no') continue;
    const flat = [];
    for (const id of w.nodes) {
      const n = osm.nodes.get(id);
      if (n) flat.push(n.x, n.y);
    }
    const link = w.tags.highway === 'motorway_link' ? 1 : 0;
    const lanes = Math.max(1, parseInt(w.tags.lanes, 10) || DEFAULT_LANES[w.tags.highway]);
    const first = flat.slice(0, 2).join();
    const last = flat.slice(-2).join();
    for (const piece of clipLine(flat, box)) {
      const pts = simplifyLine(piece, SIMPLIFY_DM);
      // A mouth is an end that meets the ordinary streets. An end the box cut is not one.
      const mouth = [
        pts.slice(0, 2).join() === first && uses.get(w.nodes[0]) === 1 ? 1 : 0,
        pts.slice(-2).join() === last && uses.get(w.nodes[w.nodes.length - 1]) === 1 ? 1 : 0
      ];
      const ll = [];
      for (let i = 0; i < pts.length; i += 2) ll.push(+proj.lat(pts[i + 1]).toFixed(6), +proj.lon(pts[i]).toFixed(6));
      rows.push({ osm: w.id, link, layer: parseInt(w.tags.layer, 10) || 0, lanes, mouth, pts: ll });
    }
  }
  rows.sort((a, b) => a.layer - b.layer || b.link - a.link || a.osm - b.osm);
  return rows.map(({ layer, ...row }) => row);
}

/**
 * @param {Array<object>} lines From `motorwayLines`.
 * @returns {string} The content file.
 */
export function ayalonScript(lines) {
  const body = lines.map((l) => '  ' + JSON.stringify(l)).join(',\n');
  return `// content/tlv_center/ayalon.js — generated by tools/ayalon.mjs. Do not edit.
// The Ayalon and its ramps, as scenery for the ground pass (js/render/ground.js). Not read by the sim. Road geometry from OpenStreetMap,
// © OpenStreetMap contributors, ODbL. Each line runs in the direction of travel, so the carriageway's median side is its left.
TLV.q.push(['motorway', { id: 'ayalon', lines: [
${body}
] }]);
`;
}

/** Reads the area and writes the file. */
function main() {
  const area = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/areas', `${AREA}.json`), 'utf8'));
  const proj = makeProjection(area.origin);
  const osm = loadSources(path.join(ROOT, 'tools/cache'), area.sources);
  projectNodes(osm.nodes, proj);
  const lines = motorwayLines(osm, boxOf(area.bbox, proj), proj);
  const text = ayalonScript(lines);
  const out = path.join(ROOT, 'content/tlv_center/ayalon.js');
  fs.writeFileSync(out, text);
  const points = lines.reduce((sum, l) => sum + l.pts.length / 2, 0);
  console.log(`${path.relative(ROOT, out)}: ${lines.length} lines, ${points} points, ${text.length} bytes`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
