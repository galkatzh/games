#!/usr/bin/env node
// tools/import.mjs — WP-MAP
// Offline importer: `node tools/import.mjs <areaId> [--fetch] [--strict]`.
//
// Identical input gives byte-identical output. `--fetch` is the only network step. For isolated runs, used by the tests,
// `--area-file <path>`, `--overlays <dir>` and `--out <dir>` redirect input and output.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { boxOf, fetchExtract, loadSources, makeProjection, projectNodes, ringArea } from './lib/osm.mjs';
import {
  attachSignals, buildGraph, buildMovements, clipRoads, connectivity, dropGarageStubs, filterRoads, finishGraph,
  gradeSeparate, mergeJunctions, overlayChains
} from './lib/graph.mjs';
import {
  BuildingIndex, RoadIndex, crossSection, normalizeEdges, prepareBuildings, separateCarriageways, setFronts
} from './lib/section.mjs';
import { buildKerbs, projectCrossings, projectStops } from './lib/kerbs.mjs';
import { bindFacades, collectPois } from './lib/pois.mjs';
import { buildLand, buildLots, buildPaths, buildTrees, buildWalls } from './lib/land.mjs';
import { applyKerbs, applyPois, applyPre, loadOverlays } from './lib/overlay.mjs';
import { encodeMap, mapScript, tableSizes } from './lib/encode.mjs';
import { buildWorld, diffMaps, loadRuntime, readMapPayload, verifyMap, writeReports } from './lib/report.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const IMPORTER_VERSION = '1.0.0';
const DEFAULT_MAP = 'tlv_center';
const ABSOLUTE_GATE_AREAS = new Set([DEFAULT_MAP]);

/** Replaces a file in one step, so a reader sees the old file or the new one and never half of either. */
function writeAtomic(file, text) {
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, file);
}

/** Reads a JSON rule file. */
function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

/** Text of `ATTRIBUTION.txt`, section 6.9. */
function attributionText(area, osmTime) {
  return [
    `Map data for "${area.title.en}" (${area.id}) is derived from OpenStreetMap.`,
    '',
    '© OpenStreetMap contributors',
    'https://www.openstreetmap.org/copyright',
    '',
    'The data is available under the Open Database License (ODbL) 1.0:',
    'https://opendatacommons.org/licenses/odbl/1-0/',
    '',
    `Extract timestamp: ${osmTime}`,
    '',
    'map.js in this directory is a derived database and is distributed under the ODbL 1.0.',
    ''
  ].join('\n');
}

/** Regenerates `data/maps/index.js` from every area that has a written map. */
function writeMapIndex(outRoot, areasDir) {
  const maps = {};
  const ids = fs.existsSync(areasDir) ? fs.readdirSync(areasDir).filter((f) => f.endsWith('.json')).sort() : [];
  for (const file of ids) {
    const area = readJson(path.join(areasDir, file));
    if (!fs.existsSync(path.join(outRoot, 'data/maps', area.id, 'map.js'))) continue;
    maps[area.id] = { src: `data/maps/${area.id}/map.js`, title: area.title, schema: [1, 0] };
  }
  const keys = Object.keys(maps);
  const def = maps[DEFAULT_MAP] ? DEFAULT_MAP : keys[0];
  const body = JSON.stringify({ default: def, maps }, null, 2);
  writeAtomic(path.join(outRoot, 'data/maps/index.js'), `// Generated by tools/import.mjs. Do not edit.\nTLV.mapIndex = ${body};\n`);
}

/** Portal, sink, cluster and short-edge counts the report carries. */
function graphFacts(G) {
  let portals = 0;
  let deadEnds = 0;
  let shortEdges = 0;
  let multiNode = 0;
  let largestCluster = 0;
  const kinds = [0, 0, 0, 0];
  for (const j of G.juncs) {
    kinds[j.kind]++;
    if (j.portal) portals++;
    if (j.arms === 1) deadEnds++;
    if (j.members.length > 1) multiNode++;
    largestCluster = Math.max(largestCluster, j.members.length);
  }
  for (const e of G.edges) if (e.lenDm < 30) shortEdges++;
  return { junctions: G.juncs.length, kinds, portals, deadEnds, multiNode, largestCluster, edges: G.edges.length, shortEdges };
}

/** Largest buildings the road won, for review: each one is drivable through. */
function hollowBuildings(blds) {
  return blds.filter((b) => b.noCollider && !b.roofOnly)
    .map((b) => ({ osm: `${'nwr'[b.osmT]}${b.osm}`, m2: Math.round(Math.abs(ringArea(b.rings[0])) / 100), name: b.nameEn || b.name, by: b.wonBy.map((w) => `w${w}`) }))
    .sort((a, b) => b.m2 - a.m2 || (a.osm < b.osm ? -1 : 1))
    .slice(0, 25);
}

/**
 * Sources `--fetch` may write: this area's own extract, or one not downloaded yet. A shared source stays frozen, because
 * `area.bbox` is not its bbox and a re-download would shrink it.
 * @param {object} area Area definition.
 * @param {string} cacheDir `tools/cache`.
 * @returns {string[]}
 */
export function sourcesToFetch(area, cacheDir) {
  return area.sources.filter((s) => s === area.id || !fs.existsSync(path.join(cacheDir, `${s}.osm.json`)));
}

/** @returns {number} The largest value in some lists, at least 0. A loop, because a spread this long can overflow the stack on a large area. */
function largest(lists) {
  let top = 0;
  for (const list of lists) {
    for (const value of list) {
      if (value > top) top = value;
    }
  }
  return top;
}

/**
 * Runs the whole pipeline for one area.
 * @param {object} opts `{ areaId, fetch, strict, areaFile, overlaysDir, outRoot, root, log }`. `failGate` fails verification on
 * purpose, for the test that a failed map stays out of the way.
 * @returns {Promise<{ok: boolean, stats: object, verify: object, mapFile: string}>}
 */
export async function runImport(opts) {
  const root = opts.root || ROOT;
  const log = opts.log || (() => {});
  const areaFile = opts.areaFile || path.join(root, 'tools/areas', `${opts.areaId}.json`);
  const area = readJson(areaFile);
  const outRoot = opts.outRoot || root;
  const overlaysDir = opts.overlaysDir || path.join(root, 'tools/overlays', area.id);
  const cacheDir = opts.cacheDir || path.join(root, 'tools/cache');

  const tagRules = readJson(path.join(root, 'tools/rules/tags.json'));
  const parkingRules = readJson(path.join(root, 'tools/rules/parking.json'));
  const kindRules = readJson(path.join(root, 'tools/rules/kinds.json'));
  const TLV = await loadRuntime(root);
  const ctxBase = { anchors: TLV.anchors, origin: area.origin };

  if (opts.fetch) {
    for (const source of sourcesToFetch(area, cacheDir)) await fetchExtract(cacheDir, source, area.bbox);
  }

  // Passes 1, 2, 3.
  const osm = loadSources(cacheDir, area.sources);
  log(`1-2 load  ${osm.stats.elements} elements, ${osm.stats.nodes} nodes, ${osm.stats.ways} ways, ${osm.stats.relations} relations`);
  const proj = makeProjection(area.origin);
  projectNodes(osm.nodes, proj);
  const box = boxOf(area.bbox, proj);
  const ctx = { ...ctxBase, proj };

  // Pass 3b.
  const overlays = loadOverlays(overlaysDir);
  const orphans = applyPre(overlays.ops, osm, ctx);

  // Passes 4 to 7.
  const filtered = filterRoads(osm);
  log(`4   roads ${filtered.ways.length} kept, dropped ${JSON.stringify(filtered.dropped)}`);
  const clipped = clipRoads(filtered.ways, osm.nodes, box);
  log(`5   clip  ${clipped.pieces.length} pieces, ${clipped.portals} portal nodes, ${clipped.outside} ways outside`);
  const graded = gradeSeparate(clipped.pieces, osm.nodes, tagRules.classOrder);
  log(`6   grade ${graded.crossings} crossings, ${graded.joined} joined at grade, ${graded.removedKm.toFixed(2)} km removed`);
  const G = buildGraph(graded.pieces, osm.nodes);
  const prepared = prepareBuildings(osm, box, tagRules);
  const index = new BuildingIndex(prepared.blds);
  G.garageStubs = dropGarageStubs(G, (x, y) => index.at(x, y).some((id) => !index.blds[id].roofOnly));
  log(`7   graph ${G.segs.filter((s) => !s.dead).length} segs, ${G.contracted} contracted, ${G.stubsRemoved} stubs and ${G.garageStubs} garage stubs removed`);

  // Passes 10, 11, 12, then 9. Normalization needs final edge direction, so it follows numbering rather than leading it.
  mergeJunctions(G);
  finishGraph(G);
  normalizeEdges(G.edges, tagRules);
  const chains = overlayChains(G);
  const moved = buildMovements(G);
  log(`10-11 ${G.juncs.length} junctions, ${G.edges.length} edges, ${moved.moves.length} moves, ${moved.unreachable} unreachable removed, ${moved.uturns} mandatory U-turns`);
  const rings = G.rings.map((r) => Number(r.radiusM.toFixed(1)));
  const signals = attachSignals(G);
  log(`12b signals ${JSON.stringify(signals)}`);

  // Passes 13, 14. Footprints (pass 15) were joined above, because the stub filter and corridors both need them.
  const separated = separateCarriageways(G, chains, index, tagRules);
  const section = crossSection(G.edges, G.juncs, index, tagRules, parkingRules, chains, osm.lanesByOverlay);
  log(`13  section ${JSON.stringify(section)}, ${separated.nodes} nodes spread, at most ${separated.maxM} m`);
  for (const w of section.overlayLanesReduced) log(`warning: pass 13 cut lanes on w${w.way} from ${w.from} to ${w.to}, which an overlay set`);
  const scc = connectivity(G);
  log(`14  SCC ${(scc.share * 100).toFixed(1)}% of ${scc.laneKm.toFixed(0)} lane-km, ${scc.components} components`);
  if (!G.edges.length) log('warning: no road survives in this bbox, so the map is valid but has nowhere to drive');

  // Passes 15 (fronts), 17, 16.
  const roads = new RoadIndex(G.edges);
  const fronts = setFronts(prepared.blds, roads, index);
  const crossings = projectCrossings(osm, G, roads, box);
  const stops = projectStops(osm, roads, box);
  let kerbs = buildKerbs(G.edges, G.juncs, crossings.xings, stops.stops, parkingRules);
  log(`15-17 ${prepared.blds.length} buildings, ${fronts} fronts, ${crossings.xings.length} crossings, ${stops.stops.length} stops, ${kerbs.length} kerb rows`);

  // Passes 18, 19, 20. Facades bind last, so a moved or added POI still gets a wall.
  const collected = collectPois(osm, box, kindRules);
  const landed = buildLand(osm, box, roads);
  const paths = buildPaths(osm, box);
  const trees = buildTrees(osm, box);
  const lots = buildLots(osm, box, roads);
  const walled = buildWalls(osm, box, G.edges, roads);
  orphans.push(...applyPois(overlays.ops, collected, ctx));
  const curated = applyKerbs(overlays.ops, kerbs, G.edges, ctx);
  kerbs = curated.kerbs;
  orphans.push(...curated.orphans);
  const bound = bindFacades(collected, prepared.blds, index, roads, TLV.anchors.normalizeName);
  log(`18  pois ${bound.pois.length}, ${JSON.stringify(bound.stats)}`);
  log(`19  land ${landed.land.length}, paths ${paths.length}, lots ${lots.length}, trees ${trees.length}, walls ${walled.walls.length}, ${JSON.stringify(walled.stats)}`);

  // Pass 21.
  const dataDir = path.join(outRoot, 'data/maps', area.id);
  const mapFile = path.join(dataDir, 'map.js');
  fs.mkdirSync(dataDir, { recursive: true });
  const previous = fs.existsSync(mapFile) ? TLV.mapCodec.decodeAll(readMapPayload(mapFile)) : null;
  const minX = box.minX / 10;
  const minY = box.minY / 10;
  const maxX = box.maxX / 10;
  const maxY = box.maxY / 10;
  const meta = {
    title: area.title,
    origin: area.origin,
    unit: 0.1,
    bbox: area.bbox,
    bounds: [minX, minY, maxX, maxY],
    osmTime: osm.osmTime,
    importer: IMPORTER_VERSION,
    overlayHash: overlays.hash,
    license: 'ODbL-1.0',
    attribution: '© OpenStreetMap contributors'
  };
  const model = {
    juncs: G.juncs,
    edges: G.edges,
    moves: G.moves,
    blds: prepared.blds,
    pois: bound.pois,
    kerbs,
    xings: crossings.xings,
    stops: stops.stops,
    trees,
    lots,
    land: landed.land,
    paths,
    walls: walled.walls
  };
  const payload = encodeMap(model, { id: area.id, meta });
  // Verified before it replaces the old map, because other work reads this file: a map that fails its gates never reaches them.
  const candidate = `${mapFile}.${process.pid}.tmp`;
  fs.writeFileSync(candidate, mapScript(payload));

  // Pass 22.
  const maxOsmId = largest([G.edges.map((e) => e.way), prepared.blds.map((b) => b.osm), bound.pois.map((p) => p.osm)]);
  const signalNodes = [...osm.nodes.values()].filter((n) => n.tags && n.tags.highway === 'traffic_signals').length;
  const kindergartens = new Set(bound.pois.filter((p) => p.amenityKindergarten).map((p) => `${p.osmT}:${p.osm}`));
  const roofs = new Set(prepared.blds.filter((b) => b.roofOnly).map((b) => `${'nwr'[b.osmT]}${b.osm}`));
  const verify = verifyMap(TLV, candidate, {
    uniqueNodes: osm.stats.nodes,
    signalNodes,
    maxOsmId,
    kindergartens,
    fenceLines: walled.lines,
    keptRings: G.keptRings,
    roofs,
    overlapAllow: tagRules.section.overlapAllow,
    hollowAllow: tagRules.section.hollowAllow,
    built: opts.overlaysDir ? null : await buildWorld(root, candidate),
    curated: !opts.overlaysDir,
    failGate: opts.failGate
  }, ABSOLUTE_GATE_AREAS.has(area.id));
  const fileBytes = fs.statSync(candidate).size;
  if (verify.ok) {
    fs.renameSync(candidate, mapFile);
    writeAtomic(path.join(dataDir, 'ATTRIBUTION.txt'), attributionText(area, osm.osmTime));
  } else {
    fs.unlinkSync(candidate);
  }

  // Pass 23.
  const stats = {
    area: area.id,
    osmTime: osm.osmTime,
    overlayHash: overlays.hash,
    source: osm.stats,
    roads: { kept: filtered.ways.length, dropped: filtered.dropped, outside: clipped.outside, portals: clipped.portals },
    grade: { crossings: graded.crossings, joined: graded.joined, removedKm: Number(graded.removedKm.toFixed(3)), sites: graded.sites },
    graph: {
      ...graphFacts(G),
      contracted: G.contracted,
      stubsRemoved: G.stubsRemoved,
      garageStubsRemoved: G.garageStubs,
      internalEdges: G.internal.length,
      internalLongest: Math.round(largest([G.internal.map((s) => s.lenDm)]) / 10),
      overlayChains: chains.length,
      roundaboutRadii: rings,
      roundaboutsKept: G.keptRings.length,
      movements: moved.moves.length,
      movementsUnreachable: moved.unreachable,
      movementsBanned: moved.banned,
      mandatoryUturns: moved.uturns,
      signals: { ...signals, nodesAfterDedupe: signalNodes, nodesOnKeptRoads: G.signalNodes.length },
      scc: { laneKm: Number(scc.laneKm.toFixed(1)), sccLaneKm: Number(scc.sccLaneKm.toFixed(1)), components: scc.components }
    },
    section: { ...section, separated, largestNoCollider: hollowBuildings(prepared.blds) },
    buildings: { count: prepared.blds.length, fronts, ...prepared.stats },
    crossings: { count: crossings.xings.length, ...crossings.stats },
    stops: { count: stops.stops.length, unplaced: stops.unplaced },
    kerbs: { rows: kerbs.length },
    pois: { count: bound.pois.length, ...bound.stats },
    land: { count: landed.land.length, ...landed.stats, lots: lots.length, paths: paths.length, trees: trees.length },
    walls: { count: walled.walls.length, ...walled.stats },
    file: { bytes: fileBytes, tables: tableSizes(payload) },
    gates: verify.gates,
    verifyDetail: verify.detail
  };
  const diff = diffMaps(previous, verify.decoded);
  const reportDir = path.join(outRoot, 'tools/reports', area.id);
  writeReports(reportDir, stats, orphans, diff);
  if (!opts.outRoot || opts.writeIndex) writeMapIndex(outRoot, path.dirname(areaFile));

  const strictFail = opts.strict ? orphans.filter((o) => o.how === 'orphan') : [];
  for (const g of verify.gates) {
    const state = g.pass ? 'pass' : g.enforced ? 'FAIL' : 'n/a ';
    log(`${state} ${g.name}: ${g.value} (want ${g.want})`);
  }
  for (const o of strictFail) log(`FAIL orphan overlay anchor ${o.source}: ${JSON.stringify(o.anchor)}`);
  return { ok: verify.ok && strictFail.length === 0, stats, verify, mapFile, diff, orphans };
}

/** Parses the command line. Arguments arrive through `process.argv`, never a shell string. */
function parseArgs(argv) {
  const opts = { fetch: false, strict: false };
  const rest = argv.slice();
  while (rest.length) {
    const a = rest.shift();
    if (a === '--fetch') opts.fetch = true;
    else if (a === '--strict') opts.strict = true;
    else if (a === '--area-file') opts.areaFile = path.resolve(rest.shift());
    else if (a === '--overlays') opts.overlaysDir = path.resolve(rest.shift());
    else if (a === '--out') opts.outRoot = path.resolve(rest.shift());
    else if (a === '--write-index') opts.writeIndex = true;
    else if (a.startsWith('--')) throw new Error(`Unknown option ${a}`);
    else opts.areaId = a;
  }
  return opts;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const opts = parseArgs(process.argv.slice(2));
  if (!opts.areaId && !opts.areaFile) {
    console.error('Usage: node tools/import.mjs <areaId> [--fetch] [--strict]');
    process.exit(2);
  }
  opts.log = console.log;
  runImport(opts).then((r) => {
    console.log(`map.js ${r.stats.file.bytes} bytes at ${r.mapFile}`);
    if (!r.ok) {
      console.error(`Gates failed:\n  ${r.verify.failures.join('\n  ')}`);
      process.exit(1);
    }
  }).catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
